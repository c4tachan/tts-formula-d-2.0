"""Generate the map registry module from maps.json.

maps.json is the single source of truth (produced by extract_maps.py). This
replaces the 2020 mod's 339 hand-written `setupXxx()` handlers. Its `thumb`
names the map's thumbnail in assets/raw/ (ui_<thumb>), kept from the menu
board the setup menu replaced.

Run:  python tools/extract/gen_registry.py
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
MAPS = ROOT / "tools" / "extract" / "maps.json"
LUA_OUT = ROOT / "src" / "fd" / "data" / "maps.lua"

BANNER = "Generated by tools/extract/gen_registry.py from maps.json; do not edit by hand."


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def gen_lua(maps):
    L = [f"-- {BANNER}", "", "local Maps = {}", "", "Maps.list = {"]
    for m in maps:
        L.append(
            "    {{ id = {}, name = {}, key = {}, category = {}, url = {} }},".format(
                lua_str(m["id"]), lua_str(m["name"]), lua_str(m["key"]),
                lua_str(m["category"]), lua_str(m["url"]),
            )
        )
    L += [
        "}",
        "",
        "Maps.byId = {}",
        "for _, m in ipairs(Maps.list) do",
        "    Maps.byId[m.id] = m",
        "end",
        "",
        "--- All maps in one category, in display order.",
        "function Maps.inCategory(category)",
        "    local out = {}",
        "    for _, m in ipairs(Maps.list) do",
        "        if m.category == category then",
        "            out[#out + 1] = m",
        "        end",
        "    end",
        "    return out",
        "end",
        "",
        "--- Image URL for a map id, or nil if the id is unknown.",
        "function Maps.urlOf(id)",
        "    local m = Maps.byId[id]",
        "    return m and m.url or nil",
        "end",
        "",
        "return Maps",
        "",
    ]
    return "\n".join(L)


def main():
    maps = json.loads(MAPS.read_text(encoding="utf-8"))
    LUA_OUT.parent.mkdir(parents=True, exist_ok=True)
    LUA_OUT.write_text(gen_lua(maps), encoding="utf-8")

    print(f"{len(maps)} maps")
    print(f"  -> {LUA_OUT.relative_to(ROOT)}  ({LUA_OUT.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
