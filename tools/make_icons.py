"""Draw the icons that mark a move's options on the board, and pin the mod to them.

TTS puts them on the board tile as decals (fd.tts.track), loading each from
the repo on GitHub at the commit that last changed the icons. A changed icon
so gets a new URL, and no client goes on showing an old one from its cache.

Each icon is a round badge -- dark edge, white ring, coloured face -- with a
glyph on it, except the collision burst, which is shaped so it reads apart
from the round ones (and from anything they mean) when it rides on one of
them as a corner badge.

Run:  python tools/make_icons.py          draw assets/icons/*.png
      git commit and push them, then
      python tools/make_icons.py --pin    point src/fd/data/icons.lua at that commit
"""
import math
import pathlib
import re
import subprocess
import sys

from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "icons"
LUA = ROOT / "src" / "fd" / "data" / "icons.lua"

BANNER = "Generated by tools/make_icons.py -- do not edit by hand."

SIZE = 256        # pixels per side of each PNG
SUPER = 4         # drawn this many times larger, then scaled down, for smooth edges

DARK = (20, 20, 20, 255)
WHITE = (255, 255, 255, 255)

# The seats' colours, as TTS's Color.fromString gives them: the start mark
# is in the colour of the car that is to move.
SEATS = {
    "White": (1.0, 1.0, 1.0),
    "Brown": (0.443, 0.231, 0.09),
    "Red": (0.856, 0.1, 0.094),
    "Orange": (0.956, 0.392, 0.113),
    "Yellow": (0.905, 0.898, 0.172),
    "Green": (0.192, 0.701, 0.168),
    "Teal": (0.129, 0.694, 0.607),
    "Blue": (0.118, 0.53, 1.0),
    "Purple": (0.627, 0.125, 0.941),
    "Pink": (0.96, 0.439, 0.807),
}


class Pen:
    """Drawing in units of the icon: (0, 0) top left, (1, 1) bottom right."""

    def __init__(self):
        self.n = SIZE * SUPER
        self.img = Image.new("RGBA", (self.n, self.n), (0, 0, 0, 0))
        self.d = ImageDraw.Draw(self.img)

    def p(self, x, y):
        return (x * self.n, y * self.n)

    def disc(self, cx, cy, r, fill):
        self.d.ellipse([self.p(cx - r, cy - r), self.p(cx + r, cy + r)], fill=fill)

    def ring(self, cx, cy, r, width, fill):
        self.d.ellipse([self.p(cx - r, cy - r), self.p(cx + r, cy + r)], outline=fill,
                       width=round(width * self.n))

    def line(self, pts, width, fill):
        """A polyline with round ends and joints."""
        self.d.line([self.p(*q) for q in pts], fill=fill, width=round(width * self.n))
        for q in pts:
            self.disc(q[0], q[1], width / 2, fill)

    def arc(self, cx, cy, r, start, end, width, fill):
        """An arc of circle, angles in degrees clockwise from 3 o'clock, with
        round ends."""
        self.d.arc([self.p(cx - r, cy - r), self.p(cx + r, cy + r)], start, end, fill=fill,
                   width=round(width * self.n))
        for a in (start, end):
            t = math.radians(a)
            rr = r - width / 2
            self.disc(cx + rr * math.cos(t), cy + rr * math.sin(t), width / 2, fill)

    def polygon(self, pts, fill):
        self.d.polygon([self.p(*q) for q in pts], fill=fill)

    def png(self, path):
        self.img.resize((SIZE, SIZE), Image.LANCZOS).save(path, optimize=True)


def rgba(c):
    return tuple(round(v * 255) for v in c) + (255,)


def badge(face):
    """The round badge every icon but the burst sits on."""
    pen = Pen()
    pen.disc(0.5, 0.5, 0.49, DARK)
    pen.disc(0.5, 0.5, 0.455, WHITE)
    pen.disc(0.5, 0.5, 0.385, face)
    return pen


def ink_for(face):
    """Dark or white, whichever stands out on `face`."""
    r, g, b = (v / 255 for v in face[:3])
    return DARK if 0.2126 * r + 0.7152 * g + 0.0722 * b > 0.6 else WHITE


def clean():
    """A full-roll move that costs nothing: a tick."""
    pen = badge((40, 175, 70, 255))
    pen.line([(0.31, 0.52), (0.445, 0.655), (0.70, 0.37)], 0.1, WHITE)
    return pen


def brake():
    """Stopping short of the roll: the brake warning light, ( ! )."""
    pen = badge((255, 180, 0, 255))
    pen.ring(0.5, 0.5, 0.2, 0.055, DARK)
    pen.arc(0.5, 0.5, 0.3, 130, 230, 0.055, DARK)
    pen.arc(0.5, 0.5, 0.3, -50, 50, 0.055, DARK)
    pen.line([(0.5, 0.40), (0.5, 0.52)], 0.06, DARK)
    pen.disc(0.5, 0.605, 0.033, DARK)
    return pen


def overshoot():
    """Leaving a corner too early: a speedometer pinned at the top."""
    face = (245, 100, 10, 255)
    pen = badge(face)
    cx, cy = 0.5, 0.56
    pen.arc(cx, cy, 0.25, 150, 390, 0.06, WHITE)
    pen.arc(cx, cy, 0.25, 335, 390, 0.06, DARK)
    t = math.radians(-35)
    pen.line([(cx, cy), (cx + 0.2 * math.cos(t), cy + 0.2 * math.sin(t))], 0.055, WHITE)
    pen.disc(cx, cy, 0.05, WHITE)
    return pen


def star(cx, cy, points, outer, inner, turn=0.0, wobble=None):
    pts = []
    for i in range(points * 2):
        a = math.pi * i / points - math.pi / 2 + turn
        r = outer if i % 2 == 0 else inner
        if wobble and i % 2 == 0:
            r *= wobble[(i // 2) % len(wobble)]
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


def collision():
    """Ending beside another car, so a collision check: a crash burst."""
    pen = Pen()
    wob = (1.0, 0.86, 0.95, 0.82, 1.0, 0.9, 0.84)
    edge = star(0.5, 0.5, 11, 0.5, 0.36, 0.1, wob)
    pen.polygon(edge, DARK)
    pen.polygon(star(0.5, 0.5, 11, 0.455, 0.325, 0.1, wob), WHITE)
    pen.polygon(star(0.5, 0.5, 11, 0.39, 0.275, 0.1, wob), (225, 30, 40, 255))
    pen.polygon(star(0.5, 0.5, 11, 0.255, 0.17, 0.1, wob), (255, 215, 40, 255))
    return pen


def out():
    """A move that puts the car out of the race: a skull."""
    pen = badge(DARK)
    # Cranium and jaw.
    pen.disc(0.5, 0.455, 0.2, WHITE)
    pen.d.rounded_rectangle([pen.p(0.395, 0.5), pen.p(0.605, 0.705)], radius=0.04 * pen.n, fill=WHITE)
    # Eyes and nose.
    pen.disc(0.425, 0.485, 0.058, DARK)
    pen.disc(0.575, 0.485, 0.058, DARK)
    pen.polygon([(0.5, 0.54), (0.47, 0.6), (0.53, 0.6)], DARK)
    # Teeth.
    for x in (0.455, 0.5, 0.545):
        pen.line([(x, 0.64), (x, 0.7)], 0.022, DARK)
    return pen


def spin():
    """Losing the last tires overshooting: the car spins, a turning arrow."""
    pen = badge((150, 60, 210, 255))
    cx, cy, r = 0.5, 0.5, 0.2
    pen.arc(cx, cy, r, 200, 470, 0.06, WHITE)
    # The head, at the arc's end (110 degrees on), pointing on round.
    t = math.radians(110)
    ex, ey = cx + (r - 0.03) * math.cos(t), cy + (r - 0.03) * math.sin(t)
    pen.polygon([(ex - 0.11, ey - 0.02), (ex + 0.03, ey - 0.1), (ex + 0.03, ey + 0.07)], WHITE)
    return pen


def damage():
    """A damage marker on the way, a black die check each: a road warning
    sign with the road cracked on it."""
    pen = badge(DARK)
    pen.polygon([(0.5, 0.2), (0.8, 0.5), (0.5, 0.8), (0.2, 0.5)], (255, 215, 40, 255))
    pen.line([(0.47, 0.32), (0.55, 0.44), (0.44, 0.53), (0.54, 0.67)], 0.045, DARK)
    return pen


def slipstream():
    """Further by slipstreaming: fast forward."""
    pen = badge((30, 135, 255, 255))
    for x in (0.33, 0.5):
        pen.line([(x, 0.33), (x + 0.15, 0.5), (x, 0.67)], 0.07, WHITE)
    return pen


def blocked():
    """Somewhere the roll gets to but the move may not end: no entry."""
    pen = badge((215, 30, 30, 255))
    pen.line([(0.3, 0.5), (0.7, 0.5)], 0.13, WHITE)
    return pen


def start(seat):
    """Where the car to move started from, in its colour: a flag."""
    face = rgba(SEATS[seat])
    pen = badge(face)
    ink = ink_for(face)
    pen.line([(0.39, 0.27), (0.39, 0.74)], 0.06, ink)
    pen.polygon([(0.39, 0.25), (0.7, 0.36), (0.39, 0.48)], ink)
    return pen


ICONS = {
    "clean": clean,
    "brake": brake,
    "overshoot": overshoot,
    "collision": collision,
    "out": out,
    "blocked": blocked,
    "spin": spin,
    "damage": damage,
    "slipstream": slipstream,
}


def draw():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, fn in ICONS.items():
        fn().png(OUT / f"{name}.png")
    for seat in SEATS:
        start(seat).png(OUT / f"start-{seat}.png")
    print(f"drew {len(ICONS) + len(SEATS)} icons in {OUT.relative_to(ROOT)}")


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def pin():
    """Write src/fd/data/icons.lua for the last commit that changed the icons,
    once that commit is on GitHub -- the URLs would not load before."""
    rel = OUT.relative_to(ROOT).as_posix()
    if git("status", "--porcelain", "--", rel):
        sys.exit(f"{rel} has changes not committed: commit and push them first")
    sha = git("log", "-1", "--format=%H", "--", rel)
    if not sha:
        sys.exit(f"no commit has {rel} yet")
    if not git("branch", "-r", "--contains", sha):
        sys.exit(f"{sha[:8]} is not on the remote yet: push it first")
    m = re.search(r"github\.com[:/](.+?)(?:\.git)?$", git("remote", "get-url", "origin"))
    if not m:
        sys.exit("origin is not a GitHub repo")
    write_lua(m.group(1), sha)
    print(f"pinned {LUA.relative_to(ROOT)} to {sha[:8]}")


def write_lua(repo, sha):
    rel = OUT.relative_to(ROOT).as_posix()
    names = sorted(p.stem for p in OUT.glob("*.png"))
    lines = [
        f"-- {BANNER}",
        "",
        "-- The icons marking a move's options on the board, served by GitHub from",
        "-- the commit that last changed them (see fd.tts.track).",
        "",
        "local Icons = {}",
        "",
        f'Icons.commit = "{sha}"',
        f'Icons.base = "https://raw.githubusercontent.com/{repo}/{sha}/{rel}/"',
        "",
        "Icons.names = {",
        *[f'    "{n}",' for n in names],
        "}",
        "",
        "--- The URL of the icon called `name`.",
        "function Icons.url(name)",
        '    return Icons.base .. name .. ".png"',
        "end",
        "",
        "return Icons",
        "",
    ]
    LUA.write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    pin() if "--pin" in sys.argv else draw()
