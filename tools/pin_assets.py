"""Point the mod at the repo's copies of its assets instead of Steam's.

assets/raw/ (see tools/extract/download_assets.py and its manifest.json) and
tracks/raw/ hold every file the mod loads. GitHub serves each one from the
commit that last changed it, so a changed file gets a new URL and no client
goes on showing an old one from its cache.

Run:  python tools/pin_assets.py
          write src/fd/data/assets.lua: the repo's copy of each Steam URL the
          Lua uses, and the UI images each object's XML names
      python tools/pin_assets.py --save
          also write a copy of the latest save with every asset URL in it
          pointing at the repo, next to it in the TTS Saves folder

Commit and push the files first: a URL for a commit GitHub hasn't got won't load.
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools" / "extract"))
from download_assets import find_save  # noqa: E402

SRC = ROOT / "src"
RAW = ROOT / "assets" / "raw"
BOARDS = ROOT / "tracks" / "raw"
MANIFEST = RAW / "manifest.json"
MAPS = ROOT / "tools" / "extract" / "maps.json"
LUA = SRC / "fd" / "data" / "assets.lua"
# Generated from the names above, so not where the Lua uses an image.
NOT_USES = {LUA, SRC / "fd" / "data" / "maps.lua"}
BANNER = "Generated by tools/pin_assets.py -- do not edit by hand."

STEAM = re.compile(r"^https?://(?:cloud-3\.steamusercontent\.com|steamusercontent-a\.akamaihd\.net)/ugc/(.+)$")
# Fields TTS runs or renders rather than loads from a URL; Save & Play
# replaces them anyway.
SCRIPT_KEYS = {"LuaScript", "LuaScriptState", "XmlUI"}


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def steam_key(url):
    """The part of a Steam URL both of its hosts share, or None."""
    m = STEAM.match(url or "")
    return m.group(1) if m else None


def repo_files():
    """steam key -> repo path, for every asset the manifest and maps.json list."""
    files = {}
    for entry in json.loads(MANIFEST.read_text(encoding="utf-8")):
        files[steam_key(entry["url"])] = RAW / entry["file"]
    for m in json.loads(MAPS.read_text(encoding="utf-8")):
        found = sorted(BOARDS.glob(m["id"] + ".*"))
        if not found:
            sys.exit(f"tracks/raw/ has no image for {m['id']}: run tools/extract/download_maps.py {m['id']}")
        files[steam_key(m["url"])] = found[0]
    return files


def pins(paths):
    """repo path -> its GitHub URL at the commit that last changed it."""
    rels = sorted({p.relative_to(ROOT).as_posix() for p in paths})
    dirty = git("status", "--porcelain", "--", *{r.rsplit("/", 1)[0] for r in rels})
    if dirty:
        sys.exit("files not committed: commit and push them first\n" + dirty)
    m = re.search(r"github\.com[:/](.+?)(?:\.git)?$", git("remote", "get-url", "origin"))
    if not m:
        sys.exit("origin is not a GitHub repo")
    base = f"https://raw.githubusercontent.com/{m.group(1)}/"
    out, pushed = {}, {}
    for rel in rels:
        sha = git("log", "-1", "--format=%H", "--", rel)
        if not sha:
            sys.exit(f"no commit has {rel} yet")
        if sha not in pushed:
            pushed[sha] = bool(git("branch", "-r", "--contains", sha))
        if not pushed[sha]:
            sys.exit(f"{sha[:8]} ({rel}) is not on the remote yet: push it first")
        out[ROOT / rel] = base + sha + "/" + rel
    return out


def ui_names():
    """object GUID -> the UI image names it needs, "-1" being Global: those its
    entry XML names, and for Global those quoted in the Lua."""
    known = {u[3:]: e["file"] for e in json.loads(MANIFEST.read_text(encoding="utf-8"))
             for u in e["use"] if u.startswith("ui:")}
    out = {}
    for xml in sorted((SRC / "entry").glob("*.xml")):
        guid = xml.name.rsplit(".", 2)[-2]
        names = set(re.findall(r'\bimage\s*=\s*"([^"]+)"', xml.read_text(encoding="utf-8")))
        names = {n for n in names if not n.startswith("http")}
        missing = names - set(known)
        if missing:
            sys.exit(f"{xml.name} names UI images the manifest lacks: {', '.join(sorted(missing))} "
                     "-- run tools/extract/download_assets.py")
        if names:
            out[guid] = names
    for lua in SRC.rglob("*.lua"):
        if lua not in NOT_USES:
            quoted = set(re.findall(r'"([^"\n]+)"', lua.read_text(encoding="utf-8")))
            out.setdefault("-1", set()).update(quoted & set(known))
    return {guid: sorted(names) for guid, names in out.items() if names}, known


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_lua(copies, ui):
    lines = [
        f"-- {BANNER}",
        "",
        "-- The repo's copies of the mod's assets, served by GitHub from the commit",
        "-- that last changed each one (see assets/raw/manifest.json). The Lua names",
        "-- an asset by the Steam URL the mod first loaded it from, and asks here for",
        "-- the copy, so a save made before the move still matches.",
        "",
        "local Assets = {}",
        "",
        "Assets.copies = {",
        *[f"    [{lua_str(k)}] = {lua_str(v)}," for k, v in sorted(copies.items())],
        "}",
        "",
        '-- The UI images each object\'s XML names, by GUID ("-1" is Global), as',
        "-- UI.setCustomAssets takes them.",
        "Assets.ui = {",
    ]
    for guid, items in sorted(ui.items()):
        lines.append(f"    [{lua_str(guid)}] = {{")
        lines += [f"        {{ name = {lua_str(n)}, url = {lua_str(u)} }}," for n, u in items]
        lines.append("    },")
    lines += [
        "}",
        "",
        "--- The repo's copy of `url`, or `url` itself if there is none. Either Steam",
        "-- host will do.",
        "function Assets.url(url)",
        '    if type(url) ~= "string" then',
        "        return url",
        "    end",
        '    local key = url:gsub("^https?://cloud%-3%.steamusercontent%.com/ugc/",',
        '        "https://steamusercontent-a.akamaihd.net/ugc/")',
        "    return Assets.copies[key] or url",
        "end",
        "",
        "--- True if `a` and `b` are the same asset, at Steam or in the repo.",
        "function Assets.same(a, b)",
        "    return a ~= nil and Assets.url(a) == Assets.url(b)",
        "end",
        "",
        "--- Give `ui` (UI, or an object's UI) the images object `guid`'s XML names,",
        "-- in place of whatever the save had. Setting them reloads the UI, so only",
        "-- when they differ.",
        "function Assets.register(ui, guid)",
        "    local want = Assets.ui[guid] or {}",
        "    local have = ui.getCustomAssets() or {}",
        "    local same = #have == #want",
        "    for i = 1, #want do",
        "        same = same and have[i].name == want[i].name and have[i].url == want[i].url",
        "    end",
        "    if not same then",
        "        ui.setCustomAssets(want)",
        "    end",
        "end",
        "",
        "return Assets",
        "",
    ]
    LUA.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def rewrite_save(urls, ui):
    """Write a copy of the latest save pointing at the repo; returns its path."""
    path, data = find_save()
    unknown = set()
    count = 0

    def assets_for(guid):
        return [{"Type": 0, "Name": n, "URL": u} for n, u in ui.get(guid, [])]

    def walk(node, guid):
        nonlocal count
        if isinstance(node, dict):
            guid = node.get("GUID", guid)
            for k, v in node.items():
                if k in SCRIPT_KEYS:
                    continue
                if k == "CustomUIAssets" and (guid == "-1" or guid in ui):
                    node[k] = assets_for(guid)
                elif isinstance(v, str):
                    key = steam_key(v)
                    if key in urls:
                        node[k] = urls[key]
                        count += 1
                    elif key:
                        unknown.add(v)
                else:
                    walk(v, guid)
        elif isinstance(node, list):
            for item in node:
                walk(item, guid)

    walk(data, "-1")
    # The board's own images, which the save may have lost.
    for obj in data.get("ObjectStates", []):
        if obj.get("GUID") in ui and obj.get("GUID") != "-1":
            obj["CustomUIAssets"] = assets_for(obj["GUID"])
    if unknown:
        print(f"{len(unknown)} Steam URLs have no copy in the repo and were left as they are:")
        for u in sorted(unknown):
            print("  " + u)
    data["SaveName"] = data.get("SaveName", "") + " (repo assets)"
    out = path.with_name(path.stem + " - repo assets.json")
    out.write_text(json.dumps(data, indent=2, ensure_ascii=False), encoding="utf-8")
    thumb = path.with_suffix(".png")
    if thumb.exists():
        out.with_suffix(".png").write_bytes(thumb.read_bytes())
    print(f"rewrote {count} URLs in {path.name} -> {out}")
    return out


def main():
    files = repo_files()
    url_of = pins(files.values())
    urls = {key: url_of[p] for key, p in files.items()}

    src_steam = set()
    for lua in SRC.rglob("*.lua"):
        if lua != LUA:
            src_steam |= {u for u in re.findall(r'"(https?://[^"]+)"', lua.read_text(encoding="utf-8"))
                          if steam_key(u)}
    missing = sorted(u for u in src_steam if steam_key(u) not in urls)
    if missing:
        sys.exit("src/ loads Steam URLs the repo has no copy of -- run tools/extract/download_assets.py:\n  "
                 + "\n  ".join(missing))
    copies = {u: urls[steam_key(u)] for u in src_steam}

    names, files_by_name = ui_names()
    ui = {guid: [(n, url_of[RAW / files_by_name[n]]) for n in ns] for guid, ns in names.items()}
    write_lua(copies, ui)
    print(f"wrote {LUA.relative_to(ROOT)}: {len(copies)} copies, "
          + ", ".join(f"{len(v)} UI images for {g}" for g, v in sorted(ui.items())))

    if "--save" in sys.argv:
        rewrite_save(urls, ui)


if __name__ == "__main__":
    main()
